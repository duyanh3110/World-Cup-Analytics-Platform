-- A CHECK cannot follow a relation or express membership in either home/away team.
-- Lock related parents so concurrent membership edits cannot bypass these checks.
CREATE FUNCTION assert_match_children(p_match_id bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE m matches%ROWTYPE;
BEGIN
    SELECT * INTO m FROM matches WHERE match_id = p_match_id FOR SHARE;
    IF NOT FOUND THEN RETURN; END IF;
    PERFORM s.tournament_squad_id FROM tournament_squads s WHERE s.tournament_squad_id IN (
        SELECT tournament_squad_id FROM match_participations WHERE match_id = p_match_id
        UNION SELECT tournament_squad_id FROM match_events WHERE match_id = p_match_id
    ) FOR SHARE;
    IF EXISTS (SELECT 1 FROM match_team_stats WHERE match_id = p_match_id
        AND team_id NOT IN (m.home_team_id, m.away_team_id)) THEN
        RAISE EXCEPTION 'Statistics team is not a participant in match %', p_match_id USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM match_participations p JOIN tournament_squads s USING (tournament_squad_id)
        WHERE p.match_id = p_match_id AND (s.tournament_id <> m.tournament_id
            OR s.team_id NOT IN (m.home_team_id, m.away_team_id))) THEN
        RAISE EXCEPTION 'Player squad is not a participant in match %', p_match_id USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM match_events e LEFT JOIN tournament_squads s USING (tournament_squad_id)
        WHERE e.match_id = p_match_id AND (
            (e.team_id IS NOT NULL AND e.team_id NOT IN (m.home_team_id, m.away_team_id))
            OR (e.tournament_squad_id IS NOT NULL AND (s.tournament_id <> m.tournament_id
                OR s.team_id NOT IN (m.home_team_id, m.away_team_id)
                OR (e.team_id IS NOT NULL AND e.team_id <> s.team_id)))
            OR (e.event_type IN ('SHOOTOUT_GOAL', 'SHOOTOUT_MISS') AND m.result_type IS DISTINCT FROM 'PENALTIES')
            OR (e.period IN ('EXTRA_TIME_FIRST_HALF', 'EXTRA_TIME_SECOND_HALF') AND m.result_type = 'REGULAR')
        )) THEN
        RAISE EXCEPTION 'Event membership or period conflicts with match %', p_match_id USING ERRCODE = '23514';
    END IF;
END $$;

CREATE FUNCTION check_match_children() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM assert_match_children(NEW.match_id);
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER check_participation_membership AFTER INSERT OR UPDATE ON match_participations
    DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_match_children();
CREATE CONSTRAINT TRIGGER check_event_membership AFTER INSERT OR UPDATE ON match_events
    DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_match_children();
CREATE CONSTRAINT TRIGGER check_stats_membership AFTER INSERT OR UPDATE ON match_team_stats
    DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_match_children();
CREATE CONSTRAINT TRIGGER check_match_membership_update AFTER UPDATE ON matches
    DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_match_children();

CREATE FUNCTION check_squad_membership_update() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE affected_match bigint;
BEGIN
    FOR affected_match IN SELECT match_id FROM match_participations WHERE tournament_squad_id = NEW.tournament_squad_id
        UNION SELECT match_id FROM match_events WHERE tournament_squad_id = NEW.tournament_squad_id
    LOOP
        PERFORM assert_match_children(affected_match);
    END LOOP;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER check_squad_membership_update AFTER UPDATE ON tournament_squads
    DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_squad_membership_update();

-- Check pre-existing children too; adding a trigger alone would not validate old rows.
DO $$
DECLARE existing_match bigint;
BEGIN
    FOR existing_match IN SELECT match_id FROM matches LOOP
        PERFORM assert_match_children(existing_match);
    END LOOP;
END $$;
